#!/usr/bin/env python3
"""Copy the shared game modules into index.html (the app is one file, no build).
   server/src/<game>.js (rules, bots; also used by the online server) and _src/<game>-ui.js (screen) are embedded
   as their own <script> blocks, just before the APP script. Run after editing either source; safe to run again."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / 'index.html').read_text()
PARTS = [('tablic.js', 'server/src/tablic.js'), ('tablic-ui.js', '_src/tablic-ui.js'),
         ('bridge.js', 'server/src/bridge.js'), ('bridge-ui.js', '_src/bridge-ui.js'),
         ('gin.js', 'server/src/gin.js'), ('gin-ui.js', '_src/gin-ui.js'),
         ('pref.js', 'server/src/pref.js'), ('pref-ui.js', '_src/pref-ui.js')]
APP = '<script>// ===================== APP (UI + game flow) ====================='
for name, path in PARTS:
    p = root / path
    if not p.exists():
        continue
    body = p.read_text().rstrip('\n')
    assert '</script' not in body, name
    block = f'<script>// @embed {name} (generated by tools/embed.py: edit {path}, not this block)\n{body}\n// @end {name}</script>\n'
    pat = re.compile(r'<script>// @embed ' + re.escape(name) + r'.*?// @end ' + re.escape(name) + r'</script>\n', re.S)
    if pat.search(html):
        html = pat.sub(lambda m: block, html, count=1)
    else:
        assert html.count(APP) == 1
        html = html.replace(APP, block + APP, 1)
(root / 'index.html').write_text(html)
print('embedded')
